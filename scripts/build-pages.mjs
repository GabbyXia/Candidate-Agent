import { readFile, writeFile, mkdir, rm, readdir, realpath, stat, copyFile } from 'node:fs/promises';
import { resolve, relative, extname, basename, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';
import { createHash } from 'node:crypto';
import { handleApi } from '../worker/api.mjs';
import { DOMAINS, CONFERENCES } from '../shared/catalog.js';

const projectRoot = fileURLToPath(new URL('../', import.meta.url));
const marker = '.talent-atlas-pages';
const json = value => JSON.stringify(value, null, 2) + '\n';
const inside = (parent, child) => { const path = relative(parent, child); return path !== '' && path !== '..' && !path.startsWith('..' + sep) && !path.startsWith(sep); };
const readJson = async path => JSON.parse(await readFile(path, 'utf8'));

async function publicationFiles(root) {
  const directory = resolve(root, 'data/published');
  let manifest;
  try { manifest = await readJson(resolve(directory, 'manifest.json')); }
  catch (error) { if (error.code === 'ENOENT') return []; throw error; }
  if (!manifest || !Array.isArray(manifest.artifacts)) throw Error('data/published/manifest.json must contain an artifacts array.');
  const allowed = new Set(['.json', '.xlsx', '.csv', '.pdf']);
  const canonicalDirectory = await realpath(directory);
  const names = new Set();
  return Promise.all(manifest.artifacts.map(async entry => {
    if (!entry || typeof entry.file !== 'string' || !entry.file || !allowed.has(extname(entry.file).toLowerCase())) throw Error('Published artifacts require a JSON, XLSX, CSV, or PDF file.');
    const source = resolve(directory, entry.file);
    if (!inside(directory, source)) throw Error('Published artifacts must stay inside data/published.');
    const canonicalSource = await realpath(source);
    if (!inside(canonicalDirectory, canonicalSource) || !(await stat(canonicalSource)).isFile()) throw Error('Published artifacts must be regular files inside data/published.');
    const filename = basename(source);
    if (!/^[A-Za-z0-9][A-Za-z0-9._-]*$/.test(filename) || names.has(filename.toLowerCase())) throw Error('Published artifact filenames must be unique and contain only letters, numbers, dots, underscores, or hyphens.');
    names.add(filename.toLowerCase());
    return { title: String(entry.title || filename), description: String(entry.description || 'Published research artifact.'), filename, type: extname(filename).slice(1).toUpperCase(), content: await readFile(canonicalSource) };
  }));
}

async function prepareOutput(output, root) {
  // A custom output may be outside the checkout, but never delete a source
  // directory or a nonempty directory that was not produced by this builder.
  const protectedDirectories = ['ui', 'data', 'worker', 'shared', 'scripts', 'tests', 'docs', 'db', 'drizzle', '.git', '.openai'].map(name => resolve(root, name));
  if (output === root || inside(output, root) || protectedDirectories.some(path => output === path || inside(path, output))) throw Error('Refusing an output path inside source files or above the project.');
  try {
    const entries = await readdir(output);
    if (entries.length && !entries.includes(marker)) throw Error('Refusing to replace a nonempty output directory without the Talent Atlas Pages marker.');
  } catch (error) { if (error.code !== 'ENOENT') throw error; }
  await rm(output, { recursive: true, force: true });
  await mkdir(output, { recursive: true });
  await writeFile(resolve(output, marker), 'Generated by scripts/build-pages.mjs\n');
}

/** Build an offline, public snapshot. Runtime secrets and server state are never read. */
export async function buildPages({ outputDir = resolve(projectRoot, 'dist-pages'), sourceRoot = projectRoot, publishedAt = new Date().toISOString() } = {}) {
  const root = resolve(sourceRoot), output = resolve(outputDir);
  if (!Number.isFinite(Date.parse(publishedAt))) throw Error('publishedAt must be a valid date.');
  publishedAt = new Date(publishedAt).toISOString();
  const additions = await publicationFiles(root);
  const [snapshots, pilot, sourcePlans] = await Promise.all([
    Promise.all(['usenix', 'networking'].map(name => readJson(resolve(root, 'data', name + '.json')))),
    readJson(resolve(root, 'data/academic-research.json')),
    readJson(resolve(root, 'data/source-plans.json')),
  ]);
  const sourceSnapshot = {
    papers: snapshots.flatMap(snapshot => snapshot.papers),
    editions: snapshots.flatMap(snapshot => snapshot.editions || (Array.isArray(snapshot.coverage) ? snapshot.coverage : snapshot.coverage?.editions) || []),
    warnings: snapshots.flatMap(snapshot => snapshot.warnings || []),
    retrievedAt: snapshots.map(snapshot => snapshot.retrievedAt || snapshot.collectedAt || snapshot.coverage?.retrievedAt).filter(Boolean).sort().at(-1),
  };
  // This GET only normalizes the checked-in snapshot. It neither accesses a
  // database nor invokes collectors, research agents, or external services.
  const response = await handleApi(new Request('https://snapshot.invalid/api/bootstrap'), { SOURCE_SNAPSHOT: sourceSnapshot, ACADEMIC_RESEARCH_SNAPSHOT: pilot });
  if (!response?.ok) throw Error('Could not build the checked-in publisher snapshot.');
  const bootstrap = await response.json();
  // A publication is an archive, so retain dated proposals even after the
  // live app's freshness window. Do not mark the archived findings as reviewed.
  const proposals = new Map((pilot.profiles || []).map(profile => [profile.candidateId, profile]));
  for (const candidate of bootstrap.candidates) if (proposals.has(candidate.id)) candidate.academicResearch = proposals.get(candidate.id);
  bootstrap.publication = { publishedAt, sourceRetrievedAt: bootstrap.coverage?.retrievedAt || sourceSnapshot.retrievedAt || null, mode: 'static_snapshot' };
  bootstrap.criteria = { ...(bootstrap.criteria || {}), dateMode: 'current_program_start', programStartYearFrom: null, programStartYearTo: null, targetGraduationYear: null };

  await prepareOutput(output, root);
  await Promise.all(['snapshot', 'downloads', 'downloads/published'].map(path => mkdir(resolve(output, path), { recursive: true })));
  const ui = resolve(root, 'ui');
  // Only browser JavaScript, CSS, and the entry HTML are deployable source.
  for (const entry of await readdir(ui, { withFileTypes: true })) {
    if (!entry.isFile() || !(entry.name === 'index.html' || ['.js', '.css'].includes(extname(entry.name)))) continue;
    if (entry.name !== 'index.html') await copyFile(resolve(ui, entry.name), resolve(output, entry.name));
  }
  let html = (await readFile(resolve(ui, 'index.html'), 'utf8'))
    .replace(/\b(src|href)=(['"])\/(?!\/)([^'"]+)\2/g, '$1=$2./$3$2')
    .replace(/data-default-view="[^"]*"/, 'data-default-view="overview"')
    .replace(/<script\b/, '<script src="./snapshot-config.js" defer></script>\n  <script');
  await writeFile(resolve(output, 'catalog.js'), (await readFile(resolve(root, 'shared/catalog.js'), 'utf8')).replace(/^export /gm, ''));
  const currentProgram = (await readFile(resolve(root, 'shared/current-program.js'), 'utf8')).replace(/^export /gm, '');
  await writeFile(resolve(output, 'current-program.js'), currentProgram);
  await Promise.all([
    writeFile(resolve(output, 'snapshot/bootstrap.json'), json(bootstrap)),
    writeFile(resolve(output, 'snapshot/profile-pilot.json'), json(pilot)),
    writeFile(resolve(output, 'snapshot/source-plans.json'), json({ plans: sourcePlans })),
    writeFile(resolve(output, 'snapshot/catalog.json'), json({ domains: DOMAINS, conferences: CONFERENCES })),
    writeFile(resolve(output, '.nojekyll'), ''),
  ]);

  const artifacts = [];
  async function artifact(filename, title, description, content, type, directory = 'downloads') {
    const path = directory + '/' + filename;
    await writeFile(resolve(output, path), content);
    const href = path + '?v=' + createHash('sha256').update(content).digest('hex').slice(0, 16);
    artifacts.push({ title, description, href, filename, type, bytes: Buffer.byteLength(content) });
  }
  await artifact('talent-atlas-snapshot.json', 'Complete research snapshot', `${bootstrap.papers.length.toLocaleString('en-US')} papers and ${bootstrap.candidates.length.toLocaleString('en-US')} provisional author profiles, with source coverage and dated research proposals.`, json(bootstrap), 'JSON');
  const context = { TextEncoder, URL };
  vm.runInNewContext(currentProgram + '\n' + await readFile(resolve(ui, 'mapping-export.js'), 'utf8'), context, { filename: 'mapping-export.js' });
  const workbook = context.buildMappingWorkbook(bootstrap, { id: 'published-snapshot', state: 'published_snapshot', stage: 'export_ready', createdAt: publishedAt, updatedAt: publishedAt, input: { role: bootstrap.coverage?.role, keywords: 'network, networking, congestion, routing, transport, datacenter' } });
  await artifact('talent-atlas-research.xlsx', 'Research workbook', 'All published profiles, papers, source citations, coverage, and review status in an Excel workbook.', Buffer.from(workbook), 'XLSX');
  await artifact('academic-research.json', 'Academic research pilot', 'Four dated, source-cited academic profile proposals. Findings remain unreviewed.', json(pilot), 'JSON');
  await artifact('source-plans.json', 'Published source plans', 'Checked-in source plan versions and their original validation evidence.', json(sourcePlans), 'JSON');
  for (const entry of additions) await artifact(entry.filename, entry.title, entry.description, entry.content, entry.type, 'downloads/published');
  const snapshotVersion = createHash('sha256').update(json(bootstrap)).digest('hex').slice(0, 16);
  const config = { ...bootstrap.publication, snapshotVersion, papers: bootstrap.papers.length, candidates: bootstrap.candidates.length, editions: bootstrap.coverage?.editions?.length || 0, artifacts };
  // Escaping angle brackets keeps generated configuration safe if a published
  // artifact title happens to contain HTML or a script-closing sequence.
  await writeFile(resolve(output, 'snapshot-config.js'), 'window.TALENT_ATLAS_STATIC=' + JSON.stringify(config).replace(/</g, '\\u003c') + ';\n');
  // Pages caches assets independently. Content versions keep one deployment's
  // HTML, shared evidence rules, UI code and styles on the same revision.
  const assetPattern = /\b(src|href)=(['"])(\.\/[^'"?#]+\.(?:js|css))\2/g;
  const versions = new Map();
  for (const [, , , href] of html.matchAll(assetPattern)) {
    const asset = resolve(output, href);
    if (!inside(output, asset)) throw Error('Browser assets must stay inside the static output.');
    versions.set(href, createHash('sha256').update(await readFile(asset)).digest('hex').slice(0, 16));
  }
  html = html.replace(assetPattern, (match, attribute, quote, href) => `${attribute}=${quote}${href}?v=${versions.get(href)}${quote}`);
  await writeFile(resolve(output, 'index.html'), html);
  return { outputDir: output, ...config };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2), options = {};
  while (args.length) {
    const arg = args.shift(), value = args.shift();
    if (!value || !['--output', '--published-at'].includes(arg)) throw Error('Usage: node scripts/build-pages.mjs [--output directory] [--published-at ISO-date]');
    options[arg === '--output' ? 'outputDir' : 'publishedAt'] = value;
  }
  const result = await buildPages(options);
  console.log(`Built GitHub Pages snapshot: ${result.papers} papers, ${result.candidates} profiles, ${result.artifacts.length} downloads in ${result.outputDir}`);
}
